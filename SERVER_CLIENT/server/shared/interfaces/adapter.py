"""Adapters report feedback; requesting a stop never proves a stopped state."""
from typing import Protocol
from shared.models.domain import RobotState


class RobotAdapter(Protocol):
    async def connect(self) -> None: ...
    async def get_state(self) -> RobotState: ...
    def capabilities(self) -> set[str]: ...
    # Canonical joint targets: direct commands are validated upstream; pose commands
    # arrive here only after IK. The adapter never assumes it must run IK.
    async def command(self, positions: dict[str, float]) -> None: ...
    async def execute_trajectory(self, trajectory: list[dict[str, float]]) -> None: ...
    async def request_stop(self) -> None: ...
    async def disconnect(self) -> None: ...
